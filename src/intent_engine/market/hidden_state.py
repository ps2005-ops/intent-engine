def summarise(before: Sequence[HiddenStateBelief],
              after: Sequence[HiddenStateBelief]) -> dict:
    """Posterior changes by company, for the session report."""
    prior = {b.subject: b.as_map for b in before}
    changes = []
    for belief in after:
        was = prior.get(belief.subject)
        if not was:
            continue
        moved = [{"state": s, "from": round(was.get(s, 0.0), 4),
                  "to": round(p, 4)}
                 for s, p in belief.distribution
                 if abs(p - was.get(s, 0.0)) >= 0.01]
        if moved:
            changes.append({"subject": belief.subject,
                            "moved": sorted(
                                moved,
                                key=lambda m: abs(m["to"] - m["from"]),
                                reverse=True)[:4],
                            "entropy": belief.entropy})
    return {"companies_tracked": len(after), "companies_moved": len(changes),
            "changes": changes}
