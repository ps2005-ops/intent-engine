"""What a company is probably DOING, inferred from what it was seen to do.

THE MODELLING CHOICE THAT MATTERS
---------------------------------
A company's strategic posture is not observable. Its actions are. So this
module keeps a probability distribution over postures and moves mass between
them as evidence arrives — it never elects a winner.

That is not a stylistic preference. "Microsoft is defending its position" is a
sentence a reader will act on; `P(DEFENDING)=0.41, P(MARKET_SHARE_SEEKING)=
0.33, P(COST_CUTTING)=0.26` is a sentence a reader will investigate. The first
is almost always overstated, because the same observable action is generated by
several postures, and the evidence usually cannot separate them.

WHY A DISTRIBUTION AND NOT A LABEL
----------------------------------
A price cut is consistent with seeking share, with excess capacity, with weak
demand, with deterring entry, and with a bundling push. Any code path that
picks one has invented the four it discarded. `observe` therefore takes a
*likelihood over states* — how well each posture explains the action — and the
posterior falls out of that, keeping every rival alive with its own mass.

CERTAINTY IS STRUCTURALLY UNREACHABLE
-------------------------------------
`_CEIL` caps any single state below 1.0 and `assert_uncertain` is available to
callers that render. There is no code path that produces "this company is
certainly X", because the underlying evidence never justifies it.
"""
